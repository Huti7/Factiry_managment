export const DICT = { en, fa }

// ── provider ────────────────────────────────────────────────────────────────
const LangCtx = createContext(null)

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try { return localStorage.getItem('flourmill-lang') || 'fa' } catch { return 'fa' }
  })

  // keep the formatting module in sync during the very first render too
  setLocale(lang)

  useEffect(() => {
    setLocale(lang)
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr'
    document.title = DICT[lang]['app.title']
    try { localStorage.setItem('flourmill-lang', lang) } catch { /* private mode */ }
  }, [lang])

  const t = (key, params) => {
    let s = DICT[lang][key] ?? DICT.en[key] ?? key
    if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v))
    return s
  }
  // L: pick a language variant from a bilingual object; pass strings through
  const L = (v) => (v == null ? '' : typeof v === 'string' ? v : v[lang] ?? v.en ?? v.fa ?? '')

  return <LangCtx.Provider value={{ lang, dir: lang === 'fa' ? 'rtl' : 'ltr', t, L, setLang }}>{children}</LangCtx.Provider>
}

export const useLang = () => useContext(LangCtx)
